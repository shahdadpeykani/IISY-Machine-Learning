import numpy as np

import matplotlib.pyplot as plt

import pandas as pd

df=np.load('/content/dataset3.npz')

df['X_train'].shape

X_train = df['X_train']
X_test = df['X_test']
y_train = df['y_train']
y_test = df['y_test']

X_train.shape

y_train.shape

y_train.sum()

from sklearn.linear_model import LogisticRegression

from sklearn.metrics import accuracy_score

LR=LogisticRegression()

LR.fit(X_train,y_train)

y_pred = LR.predict(X_test)
y_pred_train = LR.predict(X_train)

print("accuracy (test)", accuracy_score(y_test, y_pred))
print("accuracy (train)", accuracy_score(y_train, y_pred_train))

classes, counts = np.unique(y_train, return_counts=True)

proportions = counts / counts.sum()

print("Class distribution:", dict(zip(classes, counts)))
print("Uniform random baseline:", 1 / len(classes))
print("Random baseline:", np.sum(proportions ** 2))
print("Majority class baseline:", np.max(proportions))

plt.figure(figsize=(8, 6))

plt.scatter(
    X_train[:, 0],
    X_train[:, 1],
    c=y_train,
    cmap="viridis",
    alpha=0.7
)

plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.title("Dataset3")
plt.colorbar(label="Class")
plt.show()

print("Minimum:", X_train.min(axis=0))
print("Maximum:", X_train.max(axis=0))
print("Mean:", X_train.mean(axis=0))
print("Standard deviation:", X_train.std(axis=0))

from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import make_pipeline

model_scaled = make_pipeline(
    StandardScaler(),
    LogisticRegression(max_iter=2000)
)

model_scaled.fit(X_train, y_train)

train_pred = model_scaled.predict(X_train)
test_pred = model_scaled.predict(X_test)

print("Training accuracy:",
      accuracy_score(y_train, train_pred))

print("Testing accuracy:",
      accuracy_score(y_test, test_pred))

from sklearn.preprocessing import PolynomialFeatures
model_poly = make_pipeline(
    PolynomialFeatures(degree=2),
    StandardScaler(),
    LogisticRegression(max_iter=2000)
)

model_poly.fit(X_train, y_train)

train_pred = model_poly.predict(X_train)
test_pred = model_poly.predict(X_test)

print("Training accuracy:",
      accuracy_score(y_train, train_pred))

print("Testing accuracy:",
      accuracy_score(y_test, test_pred))

for c in [0.01, 0.1, 1, 10, 100]:

    model = make_pipeline(
        StandardScaler(),
        LogisticRegression(C=c, max_iter=2000)
    )

    model.fit(X_train, y_train)

    train_pred = model.predict(X_train)
    test_pred = model.predict(X_test)

    print("C:", c)

    print("Training accuracy:",
          accuracy_score(y_train, train_pred))

    print("Testing accuracy:",
          accuracy_score(y_test, test_pred))

